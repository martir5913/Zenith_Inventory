CREATE PROCEDURE [dbo].[SP_VALIDATE_USER_LOGIN]
    @Username NVARCHAR(100),
    @EncryptedPassword NVARCHAR(500),
    @IpAddress NVARCHAR(45) = NULL,
    @UserAgent NVARCHAR(1000) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    
    DECLARE @UserId INT;
    DECLARE @IsBlocked BIT = 0;
    DECLARE @FailedAttempts INT = 0;
    DECLARE @MaxAttempts INT;
    DECLARE @BlockTimeMinutes INT;
    DECLARE @LastBlockTime DATETIME2;
    DECLARE @CurrentTime DATETIME2 = GETDATE();
    DECLARE @Result NVARCHAR(50) = 'ERROR';
    DECLARE @Message NVARCHAR(500) = '';
    
    BEGIN TRY
        -- Obtener configuraciones de seguridad
        SELECT @MaxAttempts = CAST(CFG_VALOR AS INT) 
        FROM PM_CONFIGURACION 
        WHERE CFG_CLAVE = 'MAX_INTENTOS_LOGIN' AND CFG_ACTIVO = 1;
        
        SELECT @BlockTimeMinutes = CAST(CFG_VALOR AS INT) 
        FROM PM_CONFIGURACION 
        WHERE CFG_CLAVE = 'TIEMPO_BLOQUEO_MINUTOS' AND CFG_ACTIVO = 1;
        
        SET @MaxAttempts = ISNULL(@MaxAttempts, 5);
        SET @BlockTimeMinutes = ISNULL(@BlockTimeMinutes, 30);
        
        -- Buscar usuario
        SELECT 
            @UserId = USR_ID,
            @IsBlocked = USR_BLOQUEADO,
            @FailedAttempts = USR_INTENTOS_FALLIDOS,
            @LastBlockTime = USR_FECHA_BLOQUEO
        FROM PM_USUARIOS 
        WHERE USR_USERNAME = @Username AND USR_ACTIVO = 1;
        
        -- Verificar si el usuario existe
        IF @UserId IS NULL
        BEGIN
            SET @Result = 'ERROR';
            SET @Message = 'Usuario no encontrado o inactivo';
            
            -- Registrar intento fallido en bitácora
            INSERT INTO PM_BITACORA (BIT_ACCION, BIT_MODULO, BIT_DESCRIPCION, BIT_IP_ADDRESS, BIT_USER_AGENT, BIT_RESULTADO, BIT_MENSAJE_ERROR)
            VALUES ('LOGIN', 'AUTENTICACION', 'Intento de login con usuario inexistente: ' + @Username, @IpAddress, @UserAgent, 'ERROR', @Message);
            
            SELECT @Result as Resultado, @Message as Mensaje, 0 as UserId;
            RETURN;
        END
        
        -- Verificar si está bloqueado y si ya pasó el tiempo de bloqueo
        IF @IsBlocked = 1 AND @LastBlockTime IS NOT NULL
        BEGIN
            IF DATEDIFF(MINUTE, @LastBlockTime, @CurrentTime) >= @BlockTimeMinutes
            BEGIN
                -- Desbloquear usuario
                UPDATE PM_USUARIOS 
                SET USR_BLOQUEADO = 0, 
                    USR_INTENTOS_FALLIDOS = 0,
                    USR_FECHA_BLOQUEO = NULL
                WHERE USR_ID = @UserId;
                
                SET @IsBlocked = 0;
                SET @FailedAttempts = 0;
            END
            ELSE
            BEGIN
                SET @Result = 'ERROR';
                SET @Message = 'Usuario bloqueado. Intente nuevamente en ' + CAST(@BlockTimeMinutes - DATEDIFF(MINUTE, @LastBlockTime, @CurrentTime) AS NVARCHAR(10)) + ' minutos.';
                
                -- Registrar intento en usuario bloqueado
                INSERT INTO PM_BITACORA (BIT_USR_ID, BIT_ACCION, BIT_MODULO, BIT_DESCRIPCION, BIT_IP_ADDRESS, BIT_USER_AGENT, BIT_RESULTADO, BIT_MENSAJE_ERROR)
                VALUES (@UserId, 'LOGIN', 'AUTENTICACION', 'Intento de login en usuario bloqueado', @IpAddress, @UserAgent, 'ERROR', @Message);
                
                SELECT @Result as Resultado, @Message as Mensaje, 0 as UserId;
                RETURN;
            END
        END
        
        -- Verificar contraseña
        IF EXISTS (SELECT 1 FROM PM_USUARIOS WHERE USR_ID = @UserId AND USR_PASSWORD_ENCRYPTED = @EncryptedPassword)
        BEGIN
            -- Login exitoso
            UPDATE PM_USUARIOS 
            SET USR_ULTIMO_LOGIN = @CurrentTime,
                USR_INTENTOS_FALLIDOS = 0,
                USR_BLOQUEADO = 0,
                USR_FECHA_BLOQUEO = NULL
            WHERE USR_ID = @UserId;
            
            SET @Result = 'EXITO';
            SET @Message = 'Login exitoso';
            
            -- Registrar login exitoso
            INSERT INTO PM_BITACORA (BIT_USR_ID, BIT_ACCION, BIT_MODULO, BIT_DESCRIPCION, BIT_IP_ADDRESS, BIT_USER_AGENT, BIT_RESULTADO)
            VALUES (@UserId, 'LOGIN', 'AUTENTICACION', 'Login exitoso', @IpAddress, @UserAgent, 'EXITO');
            
            SELECT @Result as Resultado, @Message as Mensaje, @UserId as UserId;
        END
        ELSE
        BEGIN
            -- Contraseña incorrecta
            SET @FailedAttempts = @FailedAttempts + 1;
            
            IF @FailedAttempts >= @MaxAttempts
            BEGIN
                -- Bloquear usuario
                UPDATE PM_USUARIOS 
                SET USR_INTENTOS_FALLIDOS = @FailedAttempts,
                    USR_BLOQUEADO = 1,
                    USR_FECHA_BLOQUEO = @CurrentTime
                WHERE USR_ID = @UserId;
                
                SET @Result = 'ERROR';
                SET @Message = 'Usuario bloqueado por exceder intentos máximos de login. Intente en ' + CAST(@BlockTimeMinutes AS NVARCHAR(10)) + ' minutos.';
            END
            ELSE
            BEGIN
                -- Incrementar intentos fallidos
                UPDATE PM_USUARIOS 
                SET USR_INTENTOS_FALLIDOS = @FailedAttempts
                WHERE USR_ID = @UserId;
                
                SET @Result = 'ERROR';
                SET @Message = 'Contraseña incorrecta. Intentos restantes: ' + CAST(@MaxAttempts - @FailedAttempts AS NVARCHAR(10));
            END
            
            -- Registrar intento fallido
            INSERT INTO PM_BITACORA (BIT_USR_ID, BIT_ACCION, BIT_MODULO, BIT_DESCRIPCION, BIT_IP_ADDRESS, BIT_USER_AGENT, BIT_RESULTADO, BIT_MENSAJE_ERROR)
            VALUES (@UserId, 'LOGIN', 'AUTENTICACION', 'Intento de login fallido', @IpAddress, @UserAgent, 'ERROR', @Message);
            
            SELECT @Result as Resultado, @Message as Mensaje, 0 as UserId;
        END
        
    END TRY
    BEGIN CATCH
        SET @Result = 'ERROR';
        SET @Message = 'Error interno del sistema: ' + ERROR_MESSAGE();
        
        -- Registrar error en bitácora
        INSERT INTO PM_BITACORA (BIT_USR_ID, BIT_ACCION, BIT_MODULO, BIT_DESCRIPCION, BIT_IP_ADDRESS, BIT_USER_AGENT, BIT_RESULTADO, BIT_MENSAJE_ERROR)
        VALUES (@UserId, 'LOGIN', 'AUTENTICACION', 'Error en proceso de login', @IpAddress, @UserAgent, 'ERROR', @Message);
        
        SELECT @Result as Resultado, @Message as Mensaje, 0 as UserId;
    END CATCH
END
GO
