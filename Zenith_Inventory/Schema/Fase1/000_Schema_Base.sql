        SET @Result = 'EXITO';
        SET @Message = 'Usuario actualizado exitosamente';
        
        COMMIT TRANSACTION;
        SELECT @Result as Resultado, @Message as Mensaje;
        
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;
            
        SET @Message = 'Error al actualizar usuario: ' + ERROR_MESSAGE();
        
