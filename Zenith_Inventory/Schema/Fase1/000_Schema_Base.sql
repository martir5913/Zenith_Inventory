            USR_APELLIDO = @Apellido,
            USR_EMAIL = @Email,
            USR_TELEFONO = @Telefono,
            USR_ACTIVO = @Activo,
            USR_FECHA_MODIFICACION = GETDATE(),
            USR_USUARIO_MODIFICACION = @ModifiedBy,
            USR_IP_MODIFICACION = @IpAddress
        WHERE USR_ID = @UserId;
        
        -- Registrar en bitácora
        INSERT INTO PM_BITACORA (BIT_USR_ID, BIT_ACCION, BIT_MODULO, BIT_DESCRIPCION, BIT_IP_ADDRESS, BIT_RESULTADO)
