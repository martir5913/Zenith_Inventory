        INSERT INTO PM_BITACORA (BIT_USR_ID, BIT_ACCION, BIT_MODULO, BIT_DESCRIPCION, BIT_IP_ADDRESS, BIT_RESULTADO, BIT_MENSAJE_ERROR)
