CREATE PROCEDURE [dbo].[SP_GET_USER_INFO]
    @UserId INT
AS
BEGIN
    SET NOCOUNT ON;
    
    BEGIN TRY
        -- Información del usuario
         SELECT 
            USR_ID,
            USR_USERNAME,
            USR_NOMBRE,
            USR_APELLIDO,
            USR_EMAIL,
            USR_TELEFONO,
            USR_ACTIVO,
            USR_ULTIMO_LOGIN,
            USR_INTENTOS_FALLIDOS,
            USR_BLOQUEADO,
            USR_FECHA_BLOQUEO,
            pass_temp,
            USR_FECHA_CREACION,
            USR_USUARIO_CREACION,
            USR_FECHA_MODIFICACION,
            USR_USUARIO_MODIFICACION,
            USR_IP_CREACION,
            USR_IP_MODIFICACION
        FROM PM_USUARIOS 
        WHERE USR_ID = @UserId AND USR_ACTIVO = 1;
        
        -- Roles del usuario (CORREGIDO: Incluye ROL_ACTIVO)
        SELECT 
            r.ROL_ID,
            r.ROL_NOMBRE,
            r.ROL_DESCRIPCION,
            r.ROL_ACTIVO  -- *** CAMPO FALTANTE AGREGADO ***
        FROM PM_ROLES r
        INNER JOIN PM_USUARIOS_ROLES ur ON r.ROL_ID = ur.UR_ROL_ID
        WHERE ur.UR_USR_ID = @UserId 
        AND r.ROL_ACTIVO = 1 
        AND ur.UR_ACTIVO = 1;
        
        -- Permisos del usuario (CORREGIDO: Incluye PER_ACTIVO)
        SELECT DISTINCT
            p.PER_ID,
            p.PER_NOMBRE,
            p.PER_DESCRIPCION,
            p.PER_MODULO,
            p.PER_ACCION,
            p.PER_ACTIVO  -- *** CAMPO FALTANTE AGREGADO ***
        FROM PM_PERMISOS p
        INNER JOIN PM_ROLES_PERMISOS rp ON p.PER_ID = rp.RP_PER_ID
        INNER JOIN PM_USUARIOS_ROLES ur ON rp.RP_ROL_ID = ur.UR_ROL_ID
        WHERE ur.UR_USR_ID = @UserId 
        AND p.PER_ACTIVO = 1 
        AND rp.RP_ACTIVO = 1 
        AND ur.UR_ACTIVO = 1;
        
    END TRY
    BEGIN CATCH
        THROW;
    END CATCH
END
