JOIN SCH_GENERAL.TBL_MARCAS_EQ MA
ON M.ID_MARCA = MA.ID_MARCA
LEFT JOIN SCH_GENERAL.TBL_TIPO_SALIDA TS
ON EQ.ID_TIPO_SALIDA = TS.ID_TIPO_SALIDA
WHERE EQ.FECHA >= @FECHA_INICIO AND EQ.FECHA < DATEADD(DAY,1, @FECHA_FIN) 
		AND U.ID_UBICACION = IIF(@ID_BODEGA=0,U.ID_UBICACION,@ID_BODEGA) 
		AND E.ID_ESTADO = IIF(@ID_ESTADO_MAQUINA=0,E.ID_ESTADO,@ID_ESTADO_MAQUINA) 
		AND EQ.ID_TIPO_SALIDA = IIF(@ID_TIPO_SALIDA=0,EQ.ID_TIPO_SALIDA,@ID_TIPO_SALIDA)

END
