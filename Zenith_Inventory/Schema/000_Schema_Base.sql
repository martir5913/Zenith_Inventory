CREATE PROCEDURE [SCH_GENERAL].[SP_KARDEX]
(
@SERIE VARCHAR(256)
)
AS 
BEGIN
	SELECT 
		EQ.SERIE,
		MO.MODELO,
		MA.MARCA,
		CA.CATEGORIA,
		UB.UBICACION,

		ES.ESTADO
	FROM SCH_GENERAL.TBL_EQUIPOS EQ	
	INNER JOIN SCH_GENERAL.TBL_MODELOS MO
	ON EQ.ID_MODELO=MO.ID_MODELO
	INNER JOIN SCH_GENERAL.TBL_MARCAS_EQ MA
