CREATE PROCEDURE [SCH_GENERAL].[SP_EGRESOS_CREATE]
(
@ID_USUARIO INT,
@ID_VICE INT,
@ID_UBICACION INT,
@ID_MOTIVO_SALIDA INT,
@USUARIO varchar(20),
@HOST varchar(20),
@FECHA varchar(20),
@HORA varchar(20),
@ADJUNTO BIT,
@DESCRIPCION text,
@ESTADO bit,
@TIPO_MOVIMIENTO INT,
@DETALLE_EQUIPO [T_DETALLE_EQUIPO_EGRE] READONLY,
@RESULTADO bit output,
@MENSAJE varchar(500) output
)
AS 
BEGIN
BEGIN TRY

		DECLARE @ID_MOVIMIENTO int = 0
		SET @RESULTADO = 1
		SET @MENSAJE = ''

		BEGIN TRANSACTION REGISTRO
		INSERT INTO [SCH_GENERAL].[TBL_EGRESOS]
				   ([ID_USUARIO]
				   ,[ID_VICE]
				   ,[ID_UBICACION]
				   ,[ID_MOTIVO_SALIDA]
				   ,[USUARIO]
				   ,[HOST]
				   ,[FECHA]
				   ,[HORA]
				   ,[ADJUNTO]
				   ,[DESCRIPCION]
				   ,[ESTADO])
			 VALUES
				   (@ID_USUARIO,
					@ID_VICE,
					@ID_UBICACION,
					@ID_MOTIVO_SALIDA,
					@USUARIO,
					@HOST,
					@FECHA,
					@HORA,
					@ADJUNTO,
					@DESCRIPCION,
					@ESTADO)
		   
		   SET @ID_MOVIMIENTO = SCOPE_IDENTITY()
				
		INSERT INTO [SCH_GENERAL].TBL_DETALLE_EGRESO(ID_MOV_EGRESO,ID_EQUIPO,ESTADO)
		SELECT @ID_MOVIMIENTO,ID_EQUIPO,ESTADO from @DETALLE_EQUIPO

		UPDATE EQ SET EQ.ID_TIPO_SALIDA = DE.ID_TIPO_SALIDA,EQ.ESTADO_EQUIPO = 2
		FROM [SCH_GENERAL].[TBL_EQUIPOS] EQ
		INNER JOIN @DETALLE_EQUIPO DE on DE.ID_EQUIPO = EQ.ID_EQUIPO

		INSERT INTO SCH_GENERAL.TBL_KARDEX_EQUIPO(ID_MOV,SERIE,TIPO_MOV,ID_BODEGA,ESTADO)
		SELECT @ID_MOVIMIENTO,
		SERIE,
		--(SELECT EQ.SERIE FROM SCH_GENERAL.TBL_EQUIPOS EQ INNER JOIN @DETALLE_EQUIPO DE ON EQ.ID_EQUIPO = EQ.ID_EQUIPO WHERE EQ.ID_EQUIPO=DE.ID_EQUIPO),
		@TIPO_MOVIMIENTO,
		@ID_UBICACION,
		@ESTADO 
		FROM @DETALLE_EQUIPO

		INSERT INTO SCH_GENERAL.TBL_KARDEX_USUARIOS(ID_MOV,ID_USUARIO,TIPO_MOV,ID_BODEGA,ESTADO)
		VALUES (@ID_MOVIMIENTO,
				@ID_USUARIO,		
				@TIPO_MOVIMIENTO,
				@ID_UBICACION,
				@ESTADO) 	

		SELECT 3

		COMMIT TRANSACTION REGISTRO

	END TRY
	BEGIN CATCH
		SET @RESULTADO = 0
		SET @MENSAJE = ERROR_MESSAGE()
		SELECT 3
		ROLLBACK TRANSACTION REGISTRO
	END CATCH

END
GO
