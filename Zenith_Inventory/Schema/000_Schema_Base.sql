CREATE PROCEDURE [SCH_GENERAL].[SP_REPORTE_FILTRADO_EQUIPOS]
(
@FECHA_INICIO DATETIME,
@FECHA_FIN DATETIME,
@ID_TIPO_SALIDA INT,
@ID_BODEGA INT,
@ID_ESTADO_MAQUINA INT
)
AS BEGIN
SELECT EQ.SERIE,  U.UBICACION BODEGA, M.MODELO, MA.MARCA,ISNULL(TS.TIPO_SALIDA,'SIN SALIDA') AS 'TIPO DE SALIDA',E.ESTADO
FROM SCH_GENERAL.TBL_EQUIPOS EQ
JOIN SCH_GENERAL.TBL_ESTADO_EQUIPO E
ON EQ.ESTADO_EQUIPO = E.ID_ESTADO
JOIN SCH_GENERAL.TBL_UBICACIONES U
