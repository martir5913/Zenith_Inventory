CREATE PROCEDURE [SCH_GENERAL].[SP_SET_BODEGAS_PERMISOS]
(
@ID_AGENTE INT,
@DETALLE_BODEGAS [T_DETALLE_BODEGA] READONLY,
@RESULTADO bit output,
@MENSAJE varchar(500) output
)
AS 
BEGIN
BEGIN TRY		 
		SET @RESULTADO = 1
		SET @MENSAJE = ''

		DECLARE @tablaB TABLE(ID_AGENTE INT,ID_BODEGA INT,ACTIVO BIT)
		--Se llena la tablar temporar con un query que llama el mov egreso
		INSERT INTO @tablaB(ID_AGENTE,ID_BODEGA,ACTIVO) 
		SELECT ID_AGENTE,ID_BODEGA,ACTIVO
		FROM @DETALLE_BODEGAS

		BEGIN TRANSACTION REGISTRO			

			INSERT INTO SCH_GENERAL.TBL_PERMISO_BODEGA (ID_AGENTE,ID_ID_BODEGA,ACTIVO)
			SELECT ID_AGENTE,ID_BODEGA,ACTIVO
			FROM @tablaB TB
			WHERE NOT EXISTS(SELECT 1 FROM SCH_GENERAL.TBL_PERMISO_BODEGA WHERE ID_ID_BODEGA = TB.ID_BODEGA and ID_AGENTE=@ID_AGENTE)	
			
			UPDATE P SET ACTIVO = 0
			FROM SCH_GENERAL.TBL_PERMISO_BODEGA P
			LEFT JOIN @tablaB TB
			ON P.ID_ID_BODEGA = TB.ID_BODEGA
			WHERE TB.ID_AGENTE IS NULL AND P.ID_AGENTE=@ID_AGENTE

			UPDATE P SET ACTIVO = TB.ACTIVO
			FROM SCH_GENERAL.TBL_PERMISO_BODEGA P
			INNER JOIN @tablaB TB
			ON P.ID_ID_BODEGA = TB.ID_BODEGA
			WHERE P.ID_AGENTE=@ID_AGENTE
			
			SELECT 3

		COMMIT TRANSACTION REGISTRO

	END TRY
	BEGIN CATCH
		SET @RESULTADO = 0
		SET @MENSAJE = ERROR_MESSAGE()
		SELECT 3
		ROLLBACK TRANSACTION REGISTRO
	END CATCH
END
