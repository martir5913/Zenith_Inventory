CREATE PROCEDURE [SCH_GENERAL].[SP_SEARCH_KARDEX_USUARIO]
(
@DATO VARCHAR(128),
@TIPO BIT
)
AS BEGIN
DECLARE @ID_USUARIO INT
IF (@TIPO=1)
	BEGIN
		SET @ID_USUARIO = (SELECT ID_USUARIO FROM SCH_GENERAL.TBL_USUARIOS WHERE CODIGO= @DATO)
	END
ELSE
	BEGIN
		SET @ID_USUARIO = (SELECT ID_USUARIO FROM SCH_GENERAL.TBL_USUARIOS WHERE CONCAT(NOMBRE,' ',APELLIDO)= @DATO)
	END
--Informacion del usuario
SELECT TOP 1 U.CODIGO,U.NOMBRE,U.APELLIDO,U.PUESTO,Q.SERIE, ES.ESTADO
FROM SCH_GENERAL.TBL_KARDEX_USUARIOS K
INNER JOIN SCH_GENERAL.TBL_DETALLE_EGRESO E
ON K.ID_MOV = E.ID_MOV_EGRESO
INNER JOIN SCH_GENERAL.TBL_EQUIPOS Q
ON E.ID_EQUIPO = Q.ID_EQUIPO
INNER JOIN SCH_GENERAL.TBL_ESTADO_EQUIPO ES
ON Q.ESTADO_EQUIPO = ES.ID_ESTADO
INNER JOIN SCH_GENERAL.TBL_USUARIOS U
ON K.ID_USUARIO = U.ID_USUARIO
WHERE K.ID_USUARIO = @ID_USUARIO AND K.TIPO_MOV = 2
ORDER BY K.ID DESC
--Detalle de movimientos
SELECT K.ID_MOV,K.TIPO_MOV,T.TIPO_MOVIMIENTO 'TIPO DE MOVIMIENTO',K.ID_BODEGA,CONCAT(B.UBICACION,' - ',S.SEDE) BODEGA,K.FECHA 'FECHA REGISTRO',K.ESTADO
FROM SCH_GENERAL.TBL_KARDEX_USUARIOS K
INNER JOIN SCH_GENERAL.TBL_USUARIOS U
ON K.ID_USUARIO = U.ID_USUARIO
INNER JOIN SCH_GENERAL.TBL_TIPO_MOVIMIENTO T
ON K.TIPO_MOV = T.ID
INNER JOIN SCH_GENERAL.TBL_UBICACIONES B
ON K.ID_BODEGA = B.ID_UBICACION
INNER JOIN SCH_GENERAL.TBL_SEDES S
ON B.ID_SEDE = S.ID_SEDE
WHERE K.ID_USUARIO = @ID_USUARIO

END
