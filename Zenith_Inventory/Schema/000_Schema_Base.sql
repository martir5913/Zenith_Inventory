CREATE PROCEDURE [SCH_GENERAL].[SP_LISTAR_EQUIPOS_PAG]
(
@pag INT, 
@TamPag INT
)
As 
Begin
WITH cte
     AS (SELECT E.ID_EQUIPO,
				E.SERIE, 
				M.MODELO,
				MA.MARCA,
				SU.SUBCATEGORIA,
				C.CONTRATO, 
				ISNULL(VICE.VICEPRESIDENCIA,'SIN VICE') AS VP,
				U.UBICACION BODEGA, 
				EQ.ESTADO 'ESTADO EQUIPO',
				ISNULL(S.TIPO_SALIDA,'SIN SALIDA') AS 'TIPO DE SALIDA',
				CONVERT(varchar,E.FECHA,3) as 'FECHA INGRESO',
				E.ESTADO,
                ROW_NUMBER() OVER(
                ORDER BY E.ID_EQUIPO) AS fila
         FROM SCH_GENERAL.TBL_EQUIPOS E
		 INNER JOIN SCH_GENERAL.TBL_MODELOS M
		  ON E.ID_MODELO = M.ID_MODELO
		  INNER JOIN SCH_GENERAL.TBL_CONTRATOS C
		  ON E.ID_CONTRATO = C.ID_CONTRATO
		  INNER JOIN SCH_GENERAL.TBL_UBICACIONES U
		  ON E.ID_UBICACION = U.ID_UBICACION
		  INNER JOIN SCH_GENERAL.TBL_ESTADO_EQUIPO EQ
		  ON E.ESTADO_EQUIPO = EQ.ID_ESTADO
		  LEFT JOIN SCH_GENERAL.TBL_TIPO_SALIDA S
		  ON E.ID_TIPO_SALIDA = S.ID_TIPO_SALIDA
		  INNER JOIN SCH_GENERAL.TBL_MARCAS_EQ MA
		  ON M.ID_MARCA = MA.ID_MARCA
		  INNER JOIN SCH_GENERAL.TBL_SUBCATEGORIAS SU
		  ON M.ID_SUBCATEGORIA = SU.ID_SUBCAT
		  LEFT JOIN (SELECT DEG.ID_EQUIPO, EG.ID_VICE, V.VICEPRESIDENCIA 
						FROM SCH_GENERAL.TBL_DETALLE_EGRESO DEG 
						INNER JOIN SCH_GENERAL.TBL_EGRESOS EG 
						ON DEG.ID_MOV_EGRESO = EG.ID_MOV_EGRESO 
						INNER JOIN SCH_GENERAL.TBL_VICE V
						ON EG.ID_VICE = V.ID_VICE
						WHERE DEG.ESTADO = 1) VICE
		  ON E.ID_EQUIPO = VICE.ID_EQUIPO)
			 SELECT 
				C.ID_EQUIPO,
				C.SERIE, 
				C.MODELO,
				C.MARCA,
				C.SUBCATEGORIA,
				C.CONTRATO, 
				C.VP,
				C.BODEGA, 
				C.[ESTADO EQUIPO],
				C.[TIPO DE SALIDA],
				C.[FECHA INGRESO],
				C.ESTADO,
				C.fila
     FROM cte C
     WHERE c.fila BETWEEN
    (@pag - 1) * @TamPag + 1 
    AND @pag * @TamPag;
	SELECT  COUNT(*) AS CANTIDAD FROM SCH_GENERAL.TBL_EQUIPOS
END
GO
