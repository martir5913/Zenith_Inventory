CREATE PROCEDURE [SCH_GENERAL].[SP_INGRESOS_CREATE]
(
@USUARIO VARCHAR(25),
@HOST VARCHAR(25),
@DOMINIO varchar(25),
@ID_BODEGA INT,
@FECHA varchar(25),
@HORA varchar(25),
@DESCRIPCION text,
@ESTADO bit,
@TIPO_INGRESO varchar(128),
@TIPO_MOVIMIENTO INT,
@DETALLE_EQUIPO [T_DETALLE_EQUIPO] READONLY,
@RESULTADO bit output,
@MENSAJE varchar(500) output
)
AS 
BEGIN
BEGIN TRY

		DECLARE @ID_MOVIMIENTO int = 0
		SET @RESULTADO = 1
		SET @MENSAJE = ''

		BEGIN TRANSACTION REGISTRO

			INSERT INTO [SCH_GENERAL].[TBL_INGRESOS](USUARIO,HOST,DOMINIO,ID_BODEGA,FECHA,HORA,DESCRIPCION,ESTADO,TIPO_INGRESO)
			VALUES(@USUARIO,@HOST,@DOMINIO,@ID_BODEGA,@FECHA,@HORA,@DESCRIPCION,@ESTADO,@TIPO_INGRESO)

			SET @ID_MOVIMIENTO = SCOPE_IDENTITY()

			INSERT INTO [SCH_GENERAL].[TBL_EQUIPOS](ID_MOVIMIENTO,ID_MODELO,ID_CONTRATO,ID_UBICACION,ID_TIPO_SALIDA,SERIE,ESTADO_EQUIPO,DESCRIPCION,ESTADO)
