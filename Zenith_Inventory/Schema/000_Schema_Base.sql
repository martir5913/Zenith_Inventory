	(SELECT VISTAMENU.NOMBRE, VISTAMENU.DATO, 
		(
			SELECT SM.NOMBRE,SM.NOM_FORM FROM
			SCH_GENERAL.TBL_PERMISOS P
			INNER JOIN SCH_GENERAL.TBL_ROL R
			ON P.ID_ROL = R.ID_ROL
			INNER JOIN SCH_GENERAL.TBL_SUBMENU SM
			ON P.ID_SUBMENU = SM.ID_SUBMENU
