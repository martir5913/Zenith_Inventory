CREATE PROCEDURE [SCH_GENERAL].[SP_ESTADO_EQUIPO_UPDATE]
(
@ID_MOV_EGRESO INT,
@FECHA varchar(20),
@HORA varchar(20),
@PATH varchar(512),
@ESTADO_EQUI int,
@AGENTE varchar(80),
@ID_BODEGA INT,
@ID_USUARIO INT,
@DESCRIPCION text,
@ADJUNTO BIT,
@ESTADO BIT,
--@ESTADO_ASIGNADO INT,
@TIPO_MOVIMIENTO INT,
@RESULTADO bit output,
@MENSAJE varchar(500) output
)
AS 
BEGIN

BEGIN TRY

	DECLARE @ID_MOVIMIENTO int = 0
	SET @RESULTADO = 1
	SET @MENSAJE = ''

	BEGIN TRANSACTION REGISTRO

		INSERT INTO [SCH_GENERAL].[TBL_DEVOLUCIONES]
           ([ID_MOV_EGRESO]
           ,[FECHA]
		   ,[HORA]
		   ,[PATH]
		   ,[ESTADO_EQUI]
		   ,[AGENTE]
		   ,[DESCRIPCION]
		   ,[ADJUNTO]
           ,[ESTADO]
		   ,[ID_BODEGA])
     VALUES
           (@ID_MOV_EGRESO
           ,@FECHA
		   ,@HORA
		   ,@PATH
		   ,@ESTADO_EQUI
		   ,@AGENTE
		   ,@DESCRIPCION
		   ,@ADJUNTO
           ,@ESTADO
		   ,@ID_BODEGA)

		SET @ID_MOVIMIENTO = SCOPE_IDENTITY()
		--Se crear la tabla temporal con dos columnas
		declare @tabla table(id int,serie varchar(256))
		--Se llena la tablar temporar con un query que llama el mov egreso
		insert into @tabla(id,serie) 
		select EQ.ID_EQUIPO, EQ.SERIE
		from SCH_GENERAL.TBL_DEVOLUCIONES DE
		INNER JOIN SCH_GENERAL.TBL_DETALLE_EGRESO EG
		ON DE.ID_MOV_EGRESO=EG.ID_MOV_EGRESO
		INNER JOIN SCH_GENERAL.TBL_EQUIPOS EQ
		ON EG.ID_EQUIPO=EQ.ID_EQUIPO
		WHERE EG.ID_MOV_EGRESO=@ID_MOV_EGRESO

		INSERT INTO SCH_GENERAL.TBL_KARDEX_EQUIPO(ID_MOV,SERIE,TIPO_MOV,ID_BODEGA,ESTADO)
		SELECT @ID_MOVIMIENTO,serie,@TIPO_MOVIMIENTO,@ID_BODEGA,@ESTADO
		FROM @tabla

		INSERT INTO SCH_GENERAL.TBL_KARDEX_USUARIOS(ID_MOV,ID_USUARIO,TIPO_MOV,ID_BODEGA)
		VALUES (@ID_MOVIMIENTO,@ID_USUARIO,@TIPO_MOVIMIENTO,@ID_BODEGA)

		--Se declara una variable el cual alojara el total de filas
		declare @count int = (select count(*) from @tabla)
		--Se genera un ciclo
		while @count > 0
			BEGIN 
				declare @serie varchar(256) = (select top(1) serie from @tabla order by id)
				declare @id int = (select top(1) id from @tabla order by id)
				--declare @id_mov int = (select top(1) id_mov from @tabla order by id)
 
				UPDATE SCH_GENERAL.TBL_EQUIPOS
				SET ESTADO_EQUIPO=@ESTADO_EQUI, ID_UBICACION=@ID_BODEGA
				WHERE ID_EQUIPO=@id				

				delete @tabla where id=@id 
				set @count = (select count(*) from @tabla) 
			END

			UPDATE TBL_DETALLE_EGRESO SET ESTADO = 0
			WHERE ID_MOV_EGRESO=@ID_MOV_EGRESO

			SELECT 3
		COMMIT TRANSACTION REGISTRO

	END TRY
	BEGIN CATCH
		SET @RESULTADO = 0
		SET @MENSAJE = ERROR_MESSAGE()
		SELECT 3
		ROLLBACK TRANSACTION REGISTRO
	END CATCH 
END
GO
