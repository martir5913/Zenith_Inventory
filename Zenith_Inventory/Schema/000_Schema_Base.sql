CREATE PROCEDURE [SCH_GENERAL].[SP_DASHBOARD]
AS BEGIN
SELECT COUNT(ID_EQUIPO) EQUIPOS
FROM SCH_GENERAL.TBL_EQUIPOS

SELECT  ES.ESTADO,COUNT(*) TOTAL
FROM SCH_GENERAL.TBL_EQUIPOS EQ
INNER JOIN SCH_GENERAL.TBL_ESTADO_EQUIPO ES
ON EQ.ESTADO_EQUIPO = ES.ID_ESTADO
WHERE ESTADO_EQUIPO=1
GROUP BY ES.ESTADO

SELECT ES.ESTADO,COUNT(*) TOTAL
FROM SCH_GENERAL.TBL_EQUIPOS EQ
INNER JOIN SCH_GENERAL.TBL_ESTADO_EQUIPO ES
ON EQ.ESTADO_EQUIPO = ES.ID_ESTADO
WHERE ESTADO_EQUIPO=2
GROUP BY ES.ESTADO

SELECT ES.ESTADO,COUNT(*) TOTAL
FROM SCH_GENERAL.TBL_EQUIPOS EQ
INNER JOIN SCH_GENERAL.TBL_ESTADO_EQUIPO ES
ON EQ.ESTADO_EQUIPO = ES.ID_ESTADO
GROUP BY ES.ESTADO

SELECT COUNT(ID_USUARIO) USUARIOS
FROM SCH_GENERAL.TBL_USUARIOS

SELECT COUNT(*) AS SIN_ADJUNTO
FROM SCH_GENERAL.TBL_DETALLE_EGRESO DEG
INNER JOIN SCH_GENERAL.TBL_EGRESOS EG
ON DEG.ID_MOV_EGRESO = EG.ID_MOV_EGRESO
WHERE EG.ADJUNTO = 0

SELECT IIF(EG.ADJUNTO=1,'ADJUNTO','SIN ADJUNTO'), COUNT(*) TOTAL
FROM SCH_GENERAL.TBL_DETALLE_EGRESO DEG
INNER JOIN SCH_GENERAL.TBL_EGRESOS EG
ON DEG.ID_MOV_EGRESO = EG.ID_MOV_EGRESO
GROUP BY EG.ADJUNTO
END
