	INNER JOIN SCH_GENERAL.TBL_ESTADO_EQUIPO ES
	ON EQ.ESTADO_EQUIPO = ES.ID_ESTADO
	WHERE SERIE=@SERIE

	SELECT KA.ID_MOV,KA.ID_BODEGA,KA.TIPO_MOV, KA.SERIE,TM.TIPO_MOVIMIENTO, UB.UBICACION, KA.FECHA,KA.ESTADO
	FROM [DB_Syprosa].[SCH_GENERAL].[TBL_KARDEX_EQUIPO] KA
	INNER JOIN SCH_GENERAL.TBL_TIPO_MOVIMIENTO TM
	ON KA.TIPO_MOV = TM.ID
	INNER JOIN SCH_GENERAL.TBL_UBICACIONES UB
	ON KA.ID_BODEGA = UB.ID_UBICACION
	WHERE KA.SERIE = @SERIE

	SELECT SCOPE_IDENTITY()
	SELECT 1
